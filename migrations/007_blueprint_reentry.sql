-- Цена реентри у макетов турниров.
--
-- До этой миграции реентри считалось по взносу: в state турнира была одна
-- цена входа, и второй вход стоил столько же, сколько первый. В клубе это не
-- так — вход 800 ₽, реентри 500 ₽, — и кассу приходилось править руками у
-- каждого, кто перезашёл.
--
-- Колонка nullable, как и default_buy_in: пусто — макет цену не задаёт, и
-- турнир остаётся на своей. У турниров, сохранённых до этой правки, поля
-- reentryCost в state нет, и фронт подставляет туда взнос — деньги в уже
-- идущем вечере не пересчитываются задним числом.
--
-- Применять после 003_blueprints.sql. Идемпотентно.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.tournament_blueprints
  add column if not exists default_reentry integer check (default_reentry >= 0);

-- ── Боевые цены клуба ──────────────────────────────────────────────────────
-- Три стартовых макета переезжают на 800/500. Правим только их и только пока
-- там стоят засеянные значения: если цену уже трогали из админки, повторный
-- прогон миграции её не затрёт.
update public.tournament_blueprints
   set default_buy_in  = 800,
       default_reentry = 500,
       updated_at      = now()
 where name in ('Вятский Дейли', 'Турбо', 'Глубокий стек')
   and default_reentry is null
   and default_buy_in in (1000, 2000);

select id, name, start_stack, default_buy_in, default_reentry, sort_order
  from public.tournament_blueprints order by sort_order, id;
